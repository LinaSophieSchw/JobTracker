import psycopg

from .stellenanzeige_erfassen import anzeigenlink_bestimmen


# ==================================================
# Verbindung zur PostgreSQL-Datenbank
# ==================================================
# Die Verbindungsadresse enthält Server, Datenbankname und Zugangsdaten.
# Sie wird aus der Konfiguration übergeben und nicht im Code gespeichert.
def verbindung_oeffnen(datenbank_url):
    """Öffnet eine Verbindung zu PostgreSQL."""
    if not datenbank_url:
        raise ValueError("Die Umgebungsvariable DATABASE_URL fehlt.")

    # Bricht den Verbindungsversuch nach spätestens 15 Sekunden ab.
    return psycopg.connect(datenbank_url, connect_timeout=15)


# ==================================================
# Tabellen und Demo-Benutzer anlegen (LS)
# ==================================================
# Legt beide Tabellen und den Demo-Benutzer an.
# Die Verbindung allein erstellt noch keine Tabellen.


def tabellen_erstellen(datenbank_url):
    """Legt die benötigten Tabellen an und ergänzt den Demo-Benutzer."""
    # Bei Erfolg bestätigt psycopg die Änderungen automatisch.
    # Bei einem Fehler werden sie zurückgenommen.
    # Danach wird die Verbindung geschlossen.
    with verbindung_oeffnen(datenbank_url) as verbindung:
        verbindung.execute("""
            CREATE TABLE IF NOT EXISTS benutzer (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(100) NOT NULL
                    CHECK (length(trim(name)) > 0),
                wohnadresse_strasse VARCHAR(200),
                wohnadresse_postleitzahl VARCHAR(20),
                wohnadresse_ort VARCHAR(200),
                erstellt_am TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                geaendert_am TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        # Version 1 verwendet einen gemeinsamen Demo-Benutzer.
        # Wiederholtes Ausführen verändert ein vorhandenes Profil nicht.
        # Der Demo-Benutzer bleibt bis zu Fabios Profilerfassung bestehen. (LS)
        verbindung.execute(
            """
            INSERT INTO benutzer (
                id, name, wohnadresse_strasse,
                wohnadresse_postleitzahl, wohnadresse_ort
            )
            VALUES (%s, %s, %s, %s, %s)
            ON CONFLICT (id) DO NOTHING
            """,
            (1, "Demo-Benutzer", "Bundesplatz 3", "3005", "Bern"),
        )
        # Jede Anzeige gehört über benutzer_id zu einem Benutzer.
        # Optionale Angaben dürfen zunächst leer bleiben.
        verbindung.execute("""
            CREATE TABLE IF NOT EXISTS stellenanzeigen (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                benutzer_id INTEGER NOT NULL REFERENCES benutzer(id),

                url TEXT NOT NULL CHECK (length(trim(url)) > 0),
                titel VARCHAR(200) NOT NULL CHECK (length(trim(titel)) > 0),
                firma VARCHAR(200) NOT NULL CHECK (length(trim(firma)) > 0),
                arbeitsort VARCHAR(200),
                inseratadresse_strasse VARCHAR(200),
                inseratadresse_postleitzahl VARCHAR(20),
                inseratadresse_ort VARCHAR(200),
                pensum VARCHAR(50),
                stellenbeschreibung TEXT,

                lohn_in_chf_pro_jahr INTEGER
                    CHECK (lohn_in_chf_pro_jahr >= 0),
                status TEXT NOT NULL DEFAULT 'gespeichert'
                    CHECK (status IN (
                        'gespeichert',
                        'beworben',
                        'interview',
                        'zusage',
                        'absage',
                        'zurueckgezogen'
                    )),
                beworben_am DATE,
                notizen TEXT,
                fahrzeit_auto_in_minuten INTEGER
                    CHECK (fahrzeit_auto_in_minuten >= 0),
                strecke_auto_in_metern INTEGER
                    CHECK (strecke_auto_in_metern >= 0),

                erstellt_am TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                geaendert_am TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                UNIQUE (benutzer_id, url)
            )
        """)


# ==================================================
# Aktuellen Benutzer bestimmen
# ==================================================
def aktuelle_benutzer_id():
    """Liefert für Version 1 die ID des gemeinsamen Demo-Benutzers."""
    # Später kann hier der angemeldete Benutzer bestimmt werden.
    # Die ID übernehmen wir nicht aus den Formulareingaben.
    return 1


# ==================================================
# Wohnadresse des aktuellen Benutzers lesen (FH)
# ==================================================
# Die Arbeitswegberechnung braucht einen Startpunkt. Die Arbeitsadresse
# kommt beim Speichern aus dem Formular, die Wohnadresse aber nicht:
# Sie steht nur beim Benutzer in der Datenbank und wird hier geholt.
def wohnadresse_lesen(datenbank_url):
    """Liefert die Wohnadresse des aktuellen Benutzers in drei Teilen.

    Gibt None zurück, wenn kein Benutzer gefunden wird.
    """
    with verbindung_oeffnen(datenbank_url) as verbindung:
        ergebnis = verbindung.execute(
            """
            SELECT wohnadresse_strasse, wohnadresse_postleitzahl, wohnadresse_ort
            FROM benutzer
            WHERE id = %s
            """,
            (aktuelle_benutzer_id(),),
        ).fetchone()

    # fetchone() liefert None, wenn keine Zeile passt. Ohne diese Prüfung
    # würde ergebnis[0] mit einem schwer verständlichen Fehler abbrechen.
    if ergebnis is None:
        return None

    # Ein Dictionary mit Namen ist leichter lesbar als ergebnis[0] bis [2]:
    # Später steht im Code wohnadresse["ort"] statt wohnadresse[2].
    return {
        "strasse": ergebnis[0],
        "postleitzahl": ergebnis[1],
        "ort": ergebnis[2],
    }


# ==================================================
# Formulareingaben prüfen
# ==================================================
def textfeld_pruefen(wert, feldname, pflicht=False, maximale_laenge=None):
    """Prüft einen Textwert und wandelt leere Angaben in None um."""
    # Fehlende optionale Angaben dürfen leer bleiben.
    if wert is None:
        wert = ""

    if not isinstance(wert, str):
        raise ValueError(f"{feldname} muss ein Text sein.")

    # Entfernt Leerzeichen am Anfang und Ende.
    wert = wert.strip()

    if not wert:
        if pflicht:
            raise ValueError(f"Bitte {feldname} eingeben.")
        return None

    if maximale_laenge is not None and len(wert) > maximale_laenge:
        raise ValueError(
            f"{feldname} darf höchstens {maximale_laenge} Zeichen enthalten."
        )

    return wert


def stellenanzeige_eingaben_pruefen(daten):
    """Prüft die Formularangaben und liefert bereinigte Werte."""
    if not isinstance(daten, dict):
        raise ValueError("Bitte Anzeigenangaben übermitteln.")

    url = textfeld_pruefen(daten.get("url"), "Link", pflicht=True)

    return {
        "url": anzeigenlink_bestimmen(url),
        "titel": textfeld_pruefen(
            daten.get("titel"), "Titel", pflicht=True, maximale_laenge=200
        ),
        "firma": textfeld_pruefen(
            daten.get("firma"), "Firma", pflicht=True, maximale_laenge=200
        ),
        "arbeitsort": textfeld_pruefen(
            daten.get("arbeitsort"), "Arbeitsort", maximale_laenge=200
        ),
        # Adressen sind optional. Nur Texttyp und Maximallänge werden geprüft.
        # Es gibt keine Prüfung auf ein bestimmtes Adressformat.
        "inseratadresse_strasse": textfeld_pruefen(
            daten.get("inseratadresse_strasse"),
            "Strasse mit Hausnummer",
            maximale_laenge=200,
        ),
        "inseratadresse_postleitzahl": textfeld_pruefen(
            daten.get("inseratadresse_postleitzahl"),
            "Postleitzahl",
            maximale_laenge=20,
        ),
        "inseratadresse_ort": textfeld_pruefen(
            daten.get("inseratadresse_ort"),
            "Adressort",
            maximale_laenge=200,
        ),
        "pensum": textfeld_pruefen(daten.get("pensum"), "Pensum", maximale_laenge=50),
        "stellenbeschreibung": textfeld_pruefen(
            daten.get("stellenbeschreibung"), "Stellenbeschreibung"
        ),
    }


# ==================================================
# Stellenanzeige speichern
# ==================================================
def stellenanzeige_speichern(datenbank_url, daten):
    """Speichert geprüfte Formularwerte und liefert die neue ID."""
    geprueft = stellenanzeige_eingaben_pruefen(daten)
    benutzer_id = aktuelle_benutzer_id()

    with verbindung_oeffnen(datenbank_url) as verbindung:
        ergebnis = verbindung.execute(
            """
            INSERT INTO stellenanzeigen (
                benutzer_id, url, titel, firma, arbeitsort,
                inseratadresse_strasse,
                inseratadresse_postleitzahl,
                inseratadresse_ort,
                pensum, stellenbeschreibung
            )
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            ON CONFLICT (benutzer_id, url) DO NOTHING
            RETURNING id
            """,
            (
                benutzer_id,
                geprueft["url"],
                geprueft["titel"],
                geprueft["firma"],
                geprueft["arbeitsort"],
                geprueft["inseratadresse_strasse"],
                geprueft["inseratadresse_postleitzahl"],
                geprueft["inseratadresse_ort"],
                geprueft["pensum"],
                geprueft["stellenbeschreibung"],
            ),
        ).fetchone()

        if ergebnis is None:
            # Derselbe Link ist für diesen Benutzer bereits gespeichert.
            vorhanden = verbindung.execute(
                """
                SELECT id
                FROM stellenanzeigen
                WHERE benutzer_id = %s AND url = %s
                """,
                (benutzer_id, geprueft["url"]),
            ).fetchone()

            raise ValueError(
                f"Diese Stelle ist bereits gespeichert (ID: {vorhanden[0]})."
            )

    return ergebnis[0]


# ==================================================
# Arbeitsweg bei einer gespeicherten Stelle eintragen (FH)
# ==================================================
# Wozu: Die Stelle ist zu diesem Zeitpunkt schon gespeichert
# (stellenanzeige_speichern()). Erst danach wird der Arbeitsweg berechnet.
# Diese Funktion trägt Fahrzeit und Strecke bei der Stelle nach, damit sie
# beim späteren Öffnen ohne neue Berechnung zur Verfügung stehen.
def arbeitsweg_speichern(datenbank_url, stellen_id, arbeitsweg):
    """Trägt Fahrzeit und Strecke bei einer gespeicherten Stelle ein.

    arbeitsweg ist das Dictionary aus arbeitsweg_berechnen(), z. B.
    {"fahrzeit_auto_in_minuten": 95, "strecke_auto_in_metern": 138268}.
    Beide Werte dürfen None sein. Dann bleiben die Felder leer, weil die
    Berechnung gescheitert ist.
    """
    # 1. Verbindung zur Datenbank öffnen. Am Ende des with-Blocks werden
    #    die Änderungen bestätigt und die Verbindung geschlossen.
    with verbindung_oeffnen(datenbank_url) as verbindung:
        # 2. UPDATE ändert eine bestehende Zeile, statt eine neue anzulegen:
        #    - SET: Fahrzeit und Strecke eintragen und geaendert_am auf jetzt
        #      setzen (Regel Z1 im Datenmodell: bei jeder Änderung).
        #      Beide Werte in einem UPDATE, damit sie immer zusammenpassen.
        #    - WHERE: nur die Stelle mit dieser id, und nur, wenn sie dem
        #      aktuellen Benutzer gehört (Regel B1).
        #    Die %s sind Platzhalter; die Werte gehen getrennt mit. Das schützt
        #    vor SQL-Injection.
        verbindung.execute(
            """
            UPDATE stellenanzeigen
            SET fahrzeit_auto_in_minuten = %s,
                strecke_auto_in_metern = %s,
                geaendert_am = CURRENT_TIMESTAMP
            WHERE id = %s AND benutzer_id = %s
            """,
            (
                arbeitsweg["fahrzeit_auto_in_minuten"],
                arbeitsweg["strecke_auto_in_metern"],
                stellen_id,
                aktuelle_benutzer_id(),
            ),
        )
