# Die sechs erlaubten Werte für status, wie in Abschnitt 5 im Datenmodell
# und im CHECK der Tabelle. Eine Konstante, weil sich die Liste zur Laufzeit
# nie ändert. (MG, US 20003)
ERLAUBTE_STATUS = (
    "gespeichert",
    "beworben",
    "interview",
    "zusage",
    "absage",
    "zurueckgezogen",
)


# ==================================================
# Verbindung zur PostgreSQL-Datenbank
# ==================================================
# Die Verbindungsadresse enthält Server, Datenbankname und Zugangsdaten.
# Sie wird aus der Konfiguration übergeben und nicht im Code gespeichert.
def verbindung_oeffnen(datenbank_url):
    """Öffnet eine Verbindung zu PostgreSQL."""
    if not datenbank_url:
        raise ValueError("Die Umgebungsvariable DATABASE_URL fehlt.")

    # Bricht den Verbindungsversuch nach spätestens 15 Sekunden ab.
    return psycopg.connect(datenbank_url, connect_timeout=15)


# ==================================================
# Tabellen und Demo-Benutzer anlegen (LS)
# ==================================================
# Legt beide Tabellen und den Demo-Benutzer an.
# Die Verbindung allein erstellt noch keine Tabellen.


def tabellen_erstellen(datenbank_url):
    """Legt die benötigten Tabellen an und ergänzt den Demo-Benutzer."""
    # Bei Erfolg bestätigt psycopg die Änderungen automatisch.
    # Bei einem Fehler werden sie zurückgenommen.
    # Danach wird die Verbindung geschlossen.
    with verbindung_oeffnen(datenbank_url) as verbindung:
        verbindung.execute("""
            CREATE TABLE IF NOT EXISTS benutzer (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(100) NOT NULL
                    CHECK (length(trim(name)) > 0),
                wohnadresse_strasse VARCHAR(200),
                wohnadresse_postleitzahl VARCHAR(20),
                wohnadresse_ort VARCHAR(200),
                erstellt_am TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                geaendert_am TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        # Version 1 verwendet einen gemeinsamen Demo-Benutzer.
        # Wiederholtes Ausführen verändert ein vorhandenes Profil nicht.
        # Der Demo-Benutzer bleibt bis zu Fabios Profilerfassung bestehen. (LS)
        verbindung.execute(
            """
            INSERT INTO benutzer (
                id, name, wohnadresse_strasse,
                wohnadresse_postleitzahl, wohnadresse_ort
            )
            VALUES (%s, %s, %s, %s, %s)
            ON CONFLICT (id) DO NOTHING
            """,
            (1, "Demo-Benutzer", "Bundesplatz 3", "3005", "Bern"),
        )
        # Jede Anzeige gehört über benutzer_id zu einem Benutzer.
        # Optionale Angaben dürfen zunächst leer bleiben.
        verbindung.execute("""
            CREATE TABLE IF NOT EXISTS stellenanzeigen (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                benutzer_id INTEGER NOT NULL REFERENCES benutzer(id),

                url TEXT NOT NULL CHECK (length(trim(url)) > 0),
                titel VARCHAR(200) NOT NULL CHECK (length(trim(titel)) > 0),
                firma VARCHAR(200) NOT NULL CHECK (length(trim(firma)) > 0),
                arbeitsort VARCHAR(200),
                inseratadresse_strasse VARCHAR(200),
                inseratadresse_postleitzahl VARCHAR(20),
                inseratadresse_ort VARCHAR(200),
                pensum VARCHAR(50),
                stellenbeschreibung TEXT,

                lohn_in_chf_pro_jahr INTEGER
                    CHECK (lohn_in_chf_pro_jahr >= 0),
                status TEXT NOT NULL DEFAULT 'gespeichert'
                    CHECK (status IN (
                        'gespeichert',
                        'beworben',
                        'interview',
                        'zusage',
                        'absage',
                        'zurueckgezogen'
                    )),
                beworben_am DATE,
                notizen TEXT,
                fahrzeit_auto_in_minuten INTEGER
                    CHECK (fahrzeit_auto_in_minuten >= 0),
                strecke_auto_in_metern INTEGER
                    CHECK (strecke_auto_in_metern >= 0),

                erstellt_am TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                geaendert_am TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                UNIQUE (benutzer_id, url)
            )
        """)


